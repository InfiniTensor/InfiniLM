def test_load_aten_entries_uses_packaged_torchgen(monkeypatch):
    module = _load_generator_module()
    entries = [{"func": "relu.out(Tensor self, *, Tensor(a!) out) -> Tensor(a!)"}]
    monkeypatch.setattr(module, "_load_packaged_aten_entries", lambda: (entries, True))

    assert module._load_aten_entries("v9.9.9") == entries


def test_packaged_aten_entries_include_autogenerated_out_variants():
    module = _load_generator_module()
    entries, expanded_autogen = module._load_packaged_aten_entries()

    if not expanded_autogen:
        pytest.skip("installed torchgen does not support autogen expansion")

    relu_out_entry = next(
        entry
        for entry in module._find_out_entries(entries, "relu")
        if entry["func"].startswith("relu.out(")
    )

    assert module._parse_func(relu_out_entry["func"]).out_params


def test_packaged_aten_entries_fall_back_when_tags_are_missing(
    monkeypatch, tmp_path, capsys
):
    module = _load_generator_module()
    native_dir = tmp_path / "packaged" / "ATen" / "native"
    native_dir.mkdir(parents=True)
    native_path = native_dir / "native_functions.yaml"
    native_path.write_text(
        "- func: add.out(Tensor self, Tensor other, *, Tensor(a!) out) -> Tensor(a!)\n"
    )
    spec = types.SimpleNamespace(submodule_search_locations=[str(tmp_path)])
    monkeypatch.setattr(module.importlib.util, "find_spec", lambda name: spec)

    entries, expanded_autogen = module._load_packaged_aten_entries()

    assert expanded_autogen is False
    assert entries == [
        {"func": "add.out(Tensor self, Tensor other, *, Tensor(a!) out) -> Tensor(a!)"}
    ]
    assert "using explicit schemas only" in capsys.readouterr().err


